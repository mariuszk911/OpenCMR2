#!/usr/bin/env python3
"""Regenerates src/render/gfx_api.inc and gfx_api_prefix.h from src/port/gfx.h (run from the repo root)."""
import re

HEADER = '''/*
 * The renderer API as one X-macro list, generated from port/gfx.h by
 * tools/gen_gfx_api.py and checked against it by tests/gfx_api_list.cpp, so
 * the Amiga dispatcher (render/gfx_dispatch_amiga.cpp) and the backends'
 * prefixed exports cannot drift from the header.
 *
 *   GFX_API(return type, name, (parameters), (argument names))
 *
 * The including file defines GFX_API and undefines it afterwards.
 */
'''

text = open('src/port/gfx.h').read()
text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
lines = []
for m in re.finditer(r'([A-Za-z_][\w \*]*?)\s*\b(Gfx_\w+)\s*\(([^;{}]*?)\)\s*;', text):
    ret, name = m.group(1).strip(), m.group(2)
    params = ' '.join(m.group(3).split())
    if ret.startswith('typedef'):
        continue
    if params == 'void':
        args = ''
    else:
        args = ', '.join(re.search(r'(\w+)(\[\d*\])?$', p.strip()).group(1)
                         for p in re.split(r',\s*', params))
    lines.append('GFX_API(%s, %s, (%s), (%s))\n' % (ret, name, params, args))
with open('src/render/gfx_api.inc', 'w') as f:
    f.write(HEADER)
    f.writelines(lines)
print(len(lines), 'entries')

PREFIX_HEADER = '''/*
 * Generated by tools/gen_gfx_api.py: renames the Gfx_* API of port/gfx.h in a
 * backend's own source, so the Amiga build can link both backends into one
 * binary behind render/gfx_dispatch_amiga.cpp. Include it BEFORE port/gfx.h
 * so the declarations and the definitions are renamed alike.
 *
 *   OPENCMR2_GFX_PREFIX_MINIGL   Gfx_X -> MiniGL_Gfx_X
 *   OPENCMR2_GFX_PREFIX_CORE     Gfx_X -> Core_Gfx_X
 *
 * With neither defined the header does nothing.
 */
'''
names = [re.search(r'GFX_API\([^,]+, (Gfx_\w+)', l).group(1) for l in lines]
with open('src/render/gfx_api_prefix.h', 'w') as f:
    f.write(PREFIX_HEADER)
    for guard, prefix in (('OPENCMR2_GFX_PREFIX_MINIGL', 'MiniGL_'), ('OPENCMR2_GFX_PREFIX_CORE', 'Core_')):
        f.write('\n#ifdef %s\n' % guard)
        for n in names:
            f.write('#define %s %s%s\n' % (n, prefix, n))
        f.write('#endif\n')
